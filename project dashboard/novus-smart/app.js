// ===================== JOYSTICK =====================
let joyActive = false;
let joyRect = null;
const DEADZONE = 0.12;

function initJoystick() {
  const zone  = document.getElementById('joystickZone');
  const thumb = document.getElementById('joyThumb');
  if (!zone || !thumb) return;

  function getJoyPos(e) {
    const cx = joyRect.left + joyRect.width  / 2;
    const cy = joyRect.top  + joyRect.height / 2;
    const r  = joyRect.width / 2;
    let px = (e.clientX || (e.touches && e.touches[0].clientX)) - cx;
    let py = (e.clientY || (e.touches && e.touches[0].clientY)) - cy;
    const dist = Math.sqrt(px * px + py * py);
    if (dist > r) {
      px = (px / dist) * r;
      py = (py / dist) * r;
    }
    return { px, py, r };
  }

  function applyJoy(e) {
    if (!joyActive) return;
    joyRect = zone.getBoundingClientRect();
    const { px, py, r } = getJoyPos(e);
    const rawX =  px / r;
    const rawY = -py / r; // Invert Y so up = positive

    // Apply deadzone
    const dX = Math.abs(rawX) < DEADZONE ? 0 : rawX;
    const dY = Math.abs(rawY) < DEADZONE ? 0 : rawY;

    State.joyX = +dX.toFixed(3);
    State.joyY = +dY.toFixed(3);
    State.cmdSeq++;

    // Move thumb visually
    const halfW = joyRect.width / 2;
    const halfH = joyRect.height / 2;
    thumb.style.left = (halfW + px) + 'px';
    thumb.style.top  = (halfH + py) + 'px';

    updateJoystickUI(State.joyX, State.joyY);
  }

  function startJoy(e) {
    e.preventDefault();
    joyActive = true;
    joyRect = zone.getBoundingClientRect();
    thumb.classList.add('active');
    applyJoy(e);
  }

  function stopJoy() {
    joyActive = false;
    thumb.classList.remove('active');
    State.joyX = 0;
    State.joyY = 0;
    // Return thumb to center
    thumb.style.left = '50%';
    thumb.style.top  = '50%';
    thumb.style.transform = 'translate(-50%, -50%)';
    updateJoystickUI(0, 0);
  }

  zone.addEventListener('mousedown', startJoy);
  document.addEventListener('mousemove', applyJoy);
  document.addEventListener('mouseup', stopJoy);
  zone.addEventListener('touchstart', startJoy, { passive: false });
  document.addEventListener('touchmove', applyJoy, { passive: false });
  document.addEventListener('touchend', stopJoy);
}

function updateJoystickUI(x, y) {
  // X bar: 0→50% (left) to 50% (center) to 100% (right)
  const xPct = (x + 1) / 2 * 100;
  // Y bar: similar
  const yPct = (y + 1) / 2 * 100;

  setBarWidth('joyXBar', xPct);
  setBarWidth('joyYBar', yPct);

  const xEl = document.getElementById('joyXVal');
  const yEl = document.getElementById('joyYVal');
  if (xEl) xEl.textContent = x.toFixed(2);
  if (yEl) yEl.textContent = y.toFixed(2);

  const dirEl = document.getElementById('joyDirection');
  if (dirEl) {
    let dir = 'STOPPED';
    if (Math.abs(x) < DEADZONE && Math.abs(y) < DEADZONE) dir = 'STOPPED';
    else if (y > 0.3 && Math.abs(x) < 0.3)  dir = 'FORWARD';
    else if (y < -0.3 && Math.abs(x) < 0.3) dir = 'REVERSE';
    else if (x > 0.3 && Math.abs(y) < 0.3)  dir = 'RIGHT';
    else if (x < -0.3 && Math.abs(y) < 0.3) dir = 'LEFT';
    else if (y > 0.2 && x > 0.2)  dir = 'FWD-RIGHT';
    else if (y > 0.2 && x < -0.2) dir = 'FWD-LEFT';
    else if (y < -0.2 && x > 0.2) dir = 'REV-RIGHT';
    else if (y < -0.2 && x < -0.2) dir = 'REV-LEFT';
    dirEl.textContent = dir;
    dirEl.style.color = dir === 'STOPPED' ? 'var(--text-muted)' : 'var(--cyan)';
  }
}

