let toastTimer = null;
function showToast(msg, type = '', duration = 3000) {
  let existing = document.querySelector('.toast');
  if (existing) existing.remove();
  if (toastTimer) clearTimeout(toastTimer);

  const div = document.createElement('div');
  div.className = 'toast ' + type;
  div.textContent = msg;
  document.body.appendChild(div);
  toastTimer = setTimeout(() => div.remove(), duration);
}

// ===================== BLE MOCK =====================
function toggleBLE() {
  if (State.bleConnected) {
    disconnectBLE();
  } else {
    connectBLE();
  }
}

function connectBLE() {
  if (State.bleConnecting || State.bleConnected) return;
  if (State.mode === 'real') {
    showToast('⚠ Real BLE not available in this web demo. Switch to Simulation Mode.', 'warn', 5000);
    return;
  }
  State.bleConnecting = true;
  setBLEUI('connecting');
  showToast('🔵 Connecting to NOVUS-SIM-001...', '', 2000);

  setTimeout(() => {
    State.bleConnecting = false;
    State.bleConnected = true;
    State.controlAuthorized = false; // Must be explicitly authorized by embedded controller
    setBLEUI('connected');
    updateControlStatus();
    showToast('✓ Connected to ' + State.bleDeviceName, 'ok', 3000);
    logEvent('SYS', 'BLE connected to ' + State.bleDeviceName + ' (simulated)');
  }, 1800);
}

function disconnectBLE() {
  State.bleConnected = false;
  State.bleConnecting = false;
  State.controlAuthorized = false;
  simStop(); // Safety: send stop on BLE disconnect
  setBLEUI('disconnected');
  updateControlStatus();
  showToast('Disconnected from BLE device', 'warn', 3000);
  logEvent('SYS', 'BLE disconnected — control stopped (safety)');
}

function setBLEUI(status) {
  const dot  = document.getElementById('bleDot');
  const text = document.getElementById('bleText');
  const btn  = document.getElementById('bleToggleBtn');
  const ctrlLabel = document.getElementById('ctrlBleLabel');

  if (status === 'connecting') {
    dot.className = 'ble-dot connecting';
    text.textContent = 'Connecting...';
    btn.textContent = 'Connecting...';
    btn.className = 'ble-btn';
    if (ctrlLabel) { ctrlLabel.textContent = 'Connecting'; ctrlLabel.className = 'badge badge-warn'; }
  } else if (status === 'connected') {
    dot.className = 'ble-dot connected';
    text.textContent = State.bleDeviceName;
    btn.textContent = 'Disconnect';
    btn.className = 'ble-btn connected';
    if (ctrlLabel) { ctrlLabel.textContent = 'Connected'; ctrlLabel.className = 'badge badge-ok'; }
  } else {
    dot.className = 'ble-dot disconnected';
    text.textContent = 'Disconnected';
    btn.textContent = 'Connect BLE';
    btn.className = 'ble-btn';
    if (ctrlLabel) { ctrlLabel.textContent = 'Disconnected'; ctrlLabel.className = 'badge badge-off'; }
  }
}

// ===================== SIMULATION ENGINE =====================
let simInterval = null;
let tick = 0;

function startSimulation() {
  if (simInterval) clearInterval(simInterval);
  simInterval = setInterval(simTick, 400);
}

function simTick() {
  tick++;
  const t = tick;
  const isMoving = (Math.abs(State.joyX) > 0.05 || Math.abs(State.joyY) > 0.05);

  // Battery simulation: slow discharge
  State.battery.voltage = clamp(
    State.battery.voltage + (Math.random() - 0.52) * 0.05 + (isMoving ? -0.02 : 0.0),
    30.0, 42.0
  );
  State.battery.current = isMoving
    ? clamp(State.battery.current + (Math.random() - 0.45) * 0.3, 1.0, 14.0)
    : clamp(State.battery.current + (Math.random() - 0.55) * 0.15, 0.2, 3.5);

  State.battery.temp = clamp(
    State.battery.temp + (isMoving ? 0.02 : -0.01) + (Math.random() - 0.5) * 0.2,
    20, 58
  );

  // SOC: voltage-based estimate (36V nominal → 0-100%)
  State.battery.soc = clamp(
    Math.round(((State.battery.voltage - 30) / (42 - 30)) * 100), 0, 100
  );
  State.battery.ah = +(State.battery.soc / 100 * 10).toFixed(1);

  // Runtime estimate: remaining Ah / moving average current
  const rtMin = State.battery.current > 0.1
    ? Math.round((State.battery.ah / State.battery.current) * 60)
    : 999;
  const rtH = Math.floor(rtMin / 60);
  const rtM = rtMin % 60;
  State.battery.runtime = rtH > 0 ? `${rtH}h ${rtM}m` : `${rtMin}m`;

  // Motor simulation
  const targetRpm = isMoving
    ? Math.round(clamp(Math.abs(State.joyY) * 3500 + (Math.random() - 0.5) * 100, 0, 3500))
    : 0;
  const turnBias = State.joyX * 0.4;
  State.motors.left.rpm  = Math.max(0, Math.round(targetRpm * (1 - turnBias) + (Math.random() - 0.5) * 20));
  State.motors.right.rpm = Math.max(0, Math.round(targetRpm * (1 + turnBias) + (Math.random() - 0.5) * 20));

  State.motors.left.current  = isMoving ? +(State.motors.left.rpm / 3500 * 8 + Math.random() * 0.4).toFixed(1) : 0;
  State.motors.right.current = isMoving ? +(State.motors.right.rpm / 3500 * 8 + Math.random() * 0.4).toFixed(1) : 0;

  State.motors.left.mTemp  = clamp(State.motors.left.mTemp  + (isMoving ? 0.04 : -0.02) + (Math.random()-0.5)*0.3, 20, 80);
  State.motors.right.mTemp = clamp(State.motors.right.mTemp + (isMoving ? 0.04 : -0.02) + (Math.random()-0.5)*0.3, 20, 80);
  State.motors.left.vTemp  = clamp(State.motors.left.vTemp  + (isMoving ? 0.03 : -0.01) + (Math.random()-0.5)*0.2, 20, 80);
  State.motors.right.vTemp = clamp(State.motors.right.vTemp + (isMoving ? 0.03 : -0.01) + (Math.random()-0.5)*0.2, 20, 80);

  State.motors.left.power  = +(State.battery.voltage * State.motors.left.current).toFixed(1);
  State.motors.right.power = +(State.battery.voltage * State.motors.right.current).toFixed(1);

  // Speed from RPM (motor 170KV, roller 50mm, ~0.157m circumference)
  const avgRpm = (State.motors.left.rpm + State.motors.right.rpm) / 2;
  State.currentSpeed = +Math.min((avgRpm / 3500) * State.speedLimitKmh, State.speedLimitKmh).toFixed(1);

  // AI health score simulation
  let score = 82 + Math.sin(t * 0.05) * 5 + (Math.random() - 0.5) * 4;
  if (State.battery.soc < 30) score -= 10;
  if (State.battery.temp > 42) score -= 8;
  if (State.motors.left.mTemp > 65) score -= 6;
  State.ai.healthScore = Math.round(clamp(score, 0, 100));

  // Check warnings
  checkWarnings();

  // Update chart ringbuffers
  pushRing(ChartData.batVolt,    +State.battery.voltage.toFixed(2));
  pushRing(ChartData.batCurr,    +State.battery.current.toFixed(2));
  pushRing(ChartData.batTemp,    +State.battery.temp.toFixed(1));
  pushRing(ChartData.batEnergy,  +(State.battery.current * State.battery.voltage / 1000).toFixed(3));
  pushRing(ChartData.motorLRpm,  State.motors.left.rpm);
  pushRing(ChartData.motorRRpm,  State.motors.right.rpm);
  pushRing(ChartData.motorLAmp,  State.motors.left.current);
  pushRing(ChartData.motorRAmp,  State.motors.right.current);
  pushRing(ChartData.motorLTemp, +State.motors.left.mTemp.toFixed(1));
  pushRing(ChartData.motorRTemp, +State.motors.right.mTemp.toFixed(1));
  pushRing(ChartData.vescLTemp,  +State.motors.left.vTemp.toFixed(1));
  pushRing(ChartData.vescRTemp,  +State.motors.right.vTemp.toFixed(1));

  // Update DOM on every tick
  updateDashboard();
  updateBatteryScreen();
  updateMotorScreen();
  updateAIScreen();
  updateCharts();

  // Heartbeat counter
  if (t % 3 === 0) {
    const el = document.getElementById('ctrlHeartbeat');
    if (el) {
      const ms = Date.now() - State.heartbeatTs;
      el.textContent = ms + 'ms';
      State.heartbeatTs = Date.now();
    }
  }
}

function simStop() {
  State.joyX = 0;
  State.joyY = 0;
  State.currentSpeed = 0;
  updateJoystickUI(0, 0);
}

function pushRing(arr, val) {
  arr.push(val);
  if (arr.length > CHART_POINTS) arr.shift();
}

function clamp(val, min, max) {
  return Math.max(min, Math.min(max, val));
}

// ===================== WARNINGS =====================
const thresholds = {
  batSocLow: 25,
  batSocCrit: 10,
  batTempWarn: 45,
  batTempCrit: 60,
  batCurrMax: 15,
  motorTempWarn: 65,
  motorTempCrit: 80,
};

function checkWarnings() {
  State.warnings = [];

  if (State.battery.soc <= thresholds.batSocCrit)
    State.warnings.push({ level: 'crit', msg: `Critical battery: ${State.battery.soc}%` });
  else if (State.battery.soc <= thresholds.batSocLow)
    State.warnings.push({ level: 'warn', msg: `Low battery: ${State.battery.soc}%` });

  if (State.battery.temp >= thresholds.batTempCrit)
    State.warnings.push({ level: 'crit', msg: `Critical battery temperature: ${State.battery.temp.toFixed(1)}°C` });
  else if (State.battery.temp >= thresholds.batTempWarn)
    State.warnings.push({ level: 'warn', msg: `High battery temperature: ${State.battery.temp.toFixed(1)}°C` });

  if (State.battery.current >= thresholds.batCurrMax)
    State.warnings.push({ level: 'crit', msg: `BMS current limit reached: ${State.battery.current.toFixed(1)}A` });

  if (State.motors.left.mTemp >= thresholds.motorTempCrit)
    State.warnings.push({ level: 'crit', msg: `Left motor critical temp: ${State.motors.left.mTemp.toFixed(1)}°C` });
  else if (State.motors.left.mTemp >= thresholds.motorTempWarn)
    State.warnings.push({ level: 'warn', msg: `Left motor high temp: ${State.motors.left.mTemp.toFixed(1)}°C` });

  if (State.motors.right.mTemp >= thresholds.motorTempCrit)
    State.warnings.push({ level: 'crit', msg: `Right motor critical temp: ${State.motors.right.mTemp.toFixed(1)}°C` });
  else if (State.motors.right.mTemp >= thresholds.motorTempWarn)
    State.warnings.push({ level: 'warn', msg: `Right motor high temp: ${State.motors.right.mTemp.toFixed(1)}°C` });
}

