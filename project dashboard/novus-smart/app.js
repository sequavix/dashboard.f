// ===================== EVENT LOG =====================
function logEvent(tag, msg) {
  const log = document.getElementById('eventLog');
  if (!log) return;
  const now = new Date().toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit', second: '2-digit' });
  const tagClass = tag === 'CRIT' ? 'crit' : tag === 'WARN' ? 'warn' : 'ok';
  const row = document.createElement('div');
  row.className = 'event-row' + (tagClass === 'warn' || tagClass === 'crit' ? ' fault' : '');
  row.innerHTML = `<span class="ev-time">${now}</span><span class="ev-tag ${tagClass}">${tag}</span><span class="ev-msg">${msg}</span>`;
  log.insertBefore(row, log.firstChild);
  // Also add to anomaly log if relevant
  if (tag === 'CRIT' || tag === 'WARN') {
    const alog = document.getElementById('anomalyLog');
    if (alog) {
      const arow = document.createElement('div');
      arow.className = 'log-row warn';
      arow.innerHTML = `<span class="log-time">${now}</span><span class="log-msg">Simulated: ${msg}</span>`;
      alog.insertBefore(arow, alog.firstChild);
    }
  }
}

